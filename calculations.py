# Функция для автокорреляции
def calc_autocorr(data, max_lag=10):
    n = len(data)
    m = np.mean(data)
    var = np.sum((data - m) ** 2)
    r_k = []
    for k in range(1, max_lag + 1):
        cov = np.sum((data[:n - k] - m) * (data[k:] - m))
        r_k.append(cov / var)
    return r_k

