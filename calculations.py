# Функция для Формы 1 (отклонения считаются от эталона N=300 самой последовательности)
def calc_stats_orig(data, n_sizes, t_p_dict):
    results = []
    m_300 = np.mean(data)
    D_300 = np.var(data, ddof=1)
    sigma_300 = np.sqrt(D_300)
    nu_300 = sigma_300 / m_300
    sigma_m_300 = sigma_300 / np.sqrt(300)
    
    for n in n_sizes:
        sub = data[:n]
        m = np.mean(sub)
        D = np.var(sub, ddof=1) if n > 1 else 0
        sigma = np.sqrt(D)
        nu = sigma / m if m != 0 else 0
        
        sigma_m = sigma / np.sqrt(n)
        eps_90 = t_p_dict[0.90] * sigma_m
        eps_95 = t_p_dict[0.95] * sigma_m
        eps_99 = t_p_dict[0.99] * sigma_m
        
        # Отклонения от эталона
        dev_m = abs(m - m_300) / m_300 * 100
        dev_D = abs(D - D_300) / D_300 * 100
        dev_sigma = abs(sigma - sigma_300) / sigma_300 * 100
        dev_nu = abs(nu - nu_300) / nu_300 * 100
        dev_eps = abs(sigma_m - sigma_m_300) / sigma_m_300 * 100
        
        results.append({
            'N': n,
            'М.О. (знач)': round(m, 2), 'М.О. (%)': round(dev_m, 2),
            'Дов. 0.90': round(eps_90, 2), 'Дов. 0.95': round(eps_95, 2), 'Дов. 0.99': round(eps_99, 2),
            'Дов. инт. (%)': round(dev_eps, 2),
            'Дисперсия': f"{D:.2e}", 'Дисп. (%)': round(dev_D, 2),
            'СКО (знач)': round(sigma, 2), 'СКО (%)': round(dev_sigma, 2),
            'К-т вар. (знач)': round(nu, 4), 'К-т вар. (%)': round(dev_nu, 2)
        })
    return pd.DataFrame(results)

